#!/usr/bin/env python3
"""Recompute the structural-relaxation evidence in Supplementary Table S12.

For the systems with the largest energy deviations (BaTiO3, TiPbO3, Sb2Te3,
Bi2Te3) and the largest normalized RMSD (SiO2), compare the reference and
VASP Agent calculations:

- INCAR settings that differ (Hubbard U, dispersion, stopping criteria);
- k-point mesh actually generated by VASP (from OUTCAR);
- final energy per atom and its deviation;
- final D3 dispersion energy per atom (``Edisp`` in OUTCAR), and the deviation
  left after subtracting it;
- largest residual force in the final ionic step (from vasprun.xml).

Writes ``results/deviation_evidence.csv``. Example::

    python scripts/deviation_evidence.py --raw-dir /path/to/archive/01_structural_relaxation
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
import warnings
from pathlib import Path

import numpy as np
from pymatgen.io.vasp.outputs import Vasprun

EXPERIMENT_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(EXPERIMENT_DIR / "scripts"))
from evaluate_relax import atom_count, final_energy, read_text, select_run_dir  # noqa: E402

SYSTEMS = ["BaTiO3", "TiPbO3", "Sb2Te3", "Bi2Te3", "SiO2"]
INCAR_TAGS = ["ENCUT", "EDIFF", "EDIFFG", "LDAU", "LDAUTYPE", "LDAUL", "LDAUU", "LDAUJ", "IVDW"]


def incar_tags(directory: Path) -> dict[str, str]:
    tags = {}
    for line in read_text(directory / "INCAR").splitlines():
        line = line.split("#", 1)[0].split("!", 1)[0]
        if "=" in line:
            key, value = line.split("=", 1)
            tags[key.strip().upper()] = " ".join(value.split())
    return {tag: tags.get(tag, "") for tag in INCAR_TAGS}


def effective_ediffg(directory: Path) -> str:
    match = re.search(r"EDIFFG\s*=\s*(\S+)", read_text(directory / "OUTCAR"))
    return match.group(1) if match else ""


def kpoint_mesh(directory: Path) -> str:
    match = re.search(r"generate k-points for:\s+(\d+)\s+(\d+)\s+(\d+)", read_text(directory / "OUTCAR"))
    return "x".join(match.groups()) if match else ""


def potcars(directory: Path) -> str:
    titles = re.findall(r"TITEL\s*=\s*(.+)", read_text(directory / "OUTCAR"))
    return "; ".join(dict.fromkeys(" ".join(t.split()) for t in titles))


def final_dispersion(directory: Path) -> float | None:
    values = re.findall(r"Edisp \(eV\)\s+(\S+)", read_text(directory / "OUTCAR"))
    return float(values[-1]) if values else None


def max_final_force(directory: Path) -> float | None:
    try:
        run = Vasprun(directory / "vasprun.xml", parse_potcar_file=False, parse_dos=False, parse_eigen=False)
    except Exception:
        return None
    forces = np.array(run.ionic_steps[-1]["forces"])
    return float(np.max(np.linalg.norm(forces, axis=1)))


def describe(directory: Path) -> dict[str, object]:
    energy, _ = final_energy(directory)
    count = atom_count(directory)
    dispersion = final_dispersion(directory)
    return {
        "energy_per_atom_ev": energy / count,
        "n_atoms": count,
        "dispersion_mev_atom": None if dispersion is None else 1000.0 * dispersion / count,
        "max_force_ev_per_a": max_final_force(directory),
        "kpoint_mesh": kpoint_mesh(directory),
        "effective_ediffg": effective_ediffg(directory),
        "potcars": potcars(directory),
        **incar_tags(directory),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--raw-dir", type=Path, required=True, help="archive directory 01_structural_relaxation")
    parser.add_argument("--out", type=Path, default=EXPERIMENT_DIR / "results" / "deviation_evidence.csv")
    args = parser.parse_args()
    warnings.filterwarnings("ignore")

    rows = []
    for system in SYSTEMS:
        ref = describe(args.raw_dir / "pymatgen_reference" / system)
        agent = describe(select_run_dir(args.raw_dir / "vasp_agent" / system))
        delta = 1000.0 * (agent["energy_per_atom_ev"] - ref["energy_per_atom_ev"])
        dispersion = agent["dispersion_mev_atom"]
        row = {
            "system": system,
            "delta_e_mev_atom": round(delta, 2),
            "agent_dispersion_mev_atom": "" if dispersion is None else round(dispersion, 2),
            "delta_minus_dispersion_mev_atom": "" if dispersion is None else round(delta - dispersion, 2),
        }
        for label, data in (("reference", ref), ("agent", agent)):
            for key, value in data.items():
                if key in ("energy_per_atom_ev", "dispersion_mev_atom"):
                    continue
                if key == "max_force_ev_per_a" and value is not None:
                    value = round(value, 4)
                row[f"{label}_{key.lower()}"] = "" if value is None else value
        rows.append(row)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    for row in rows:
        print(row["system"], row["delta_e_mev_atom"], row["agent_dispersion_mev_atom"], row["delta_minus_dispersion_mev_atom"],
              row["reference_max_force_ev_per_a"], row["agent_max_force_ev_per_a"], row["reference_kpoint_mesh"], row["agent_kpoint_mesh"])


if __name__ == "__main__":
    main()
