#!/usr/bin/env python3
"""Recompute the band-gap evidence in Supplementary Table S12.

For the three largest band-gap deviations (BN, SnO2, diamond C), compare the
reference and VASP Agent HSE calculations:

- k-point mesh generated by VASP, ENCUT, and PRECFOCK;
- band gap, band-edge k-points, and direct/indirect character;
- the gap obtained inside the Agent output at the reference band-edge k-point
  pair, when both points are present in the Agent mesh. For BN this separates
  the effect of the denser mesh sampling a higher valence-band maximum from the
  remaining difference;
- signed differences from the literature gaps in ``LITERATURE_GAPS_EV``.

Writes ``results/deviation_evidence.csv``. Example::

    python scripts/deviation_evidence.py --raw-dir /path/to/archive/02_bandgap
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
import warnings
from pathlib import Path

import numpy as np
from pymatgen.electronic_structure.core import Spin
from pymatgen.io.vasp.outputs import Vasprun

EXPERIMENT_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(EXPERIMENT_DIR / "scripts"))
from evaluate_bandgap import agent_hse_dir  # noqa: E402

SYSTEMS = ["BN", "SnO2", "C"]
OCCUPIED = 0.5


def read_text(path: Path) -> str:
    try:
        return path.read_text(errors="ignore")
    except OSError:
        return ""


def incar_value(directory: Path, tag: str) -> str:
    for line in read_text(directory / "INCAR").splitlines():
        line = line.split("#", 1)[0]
        if "=" in line and line.split("=", 1)[0].strip().upper() == tag:
            return line.split("=", 1)[1].strip()
    return ""


def effective_precfock(directory: Path) -> str:
    """PRECFOCK as used by VASP (the OUTCAR parameter echo), including the default."""
    match = re.search(r"PRECFOCK=(\w+)\s+Normal, Fast", read_text(directory / "OUTCAR"))
    return match.group(1).capitalize() if match else ""


def kpoint_mesh(directory: Path) -> str:
    match = re.search(r"generate k-points for:\s+(\d+)\s+(\d+)\s+(\d+)", read_text(directory / "OUTCAR"))
    return "x".join(match.groups()) if match else ""


def band_edges(run: Vasprun) -> dict[str, object]:
    eig = run.eigenvalues[Spin.up]  # ISPIN = 1 in all three calculations
    energies, occupations = eig[..., 0], eig[..., 1]
    occ = np.where(occupations > OCCUPIED, energies, -np.inf)
    unocc = np.where(occupations <= OCCUPIED, energies, np.inf)
    vbm_k, cbm_k = int(np.argmax(occ.max(axis=1))), int(np.argmin(unocc.min(axis=1)))
    return {
        "kpoints": np.array(run.actual_kpoints),
        "occ_max": occ.max(axis=1),
        "unocc_min": unocc.min(axis=1),
        "vbm_k": vbm_k,
        "cbm_k": cbm_k,
        "gap": float(unocc.min() - occ.max()),
    }


def find_kpoint(kpoints: np.ndarray, target: np.ndarray) -> int | None:
    diff = kpoints - target
    diff -= np.round(diff)
    hits = np.where(np.all(np.abs(diff) < 1e-4, axis=1))[0]
    return int(hits[0]) if len(hits) else None


def kfmt(k: np.ndarray) -> str:
    return "(" + ", ".join(f"{x:.3f}" for x in k) + ")"


# Literature band gaps (eV):
# BN   6.08  inferred single-particle gap of bulk h-BN; Cassabois, Valvin, Gil, Nat. Photonics 10, 262 (2016)
# SnO2 3.6   commonly cited bulk rutile gap (approximate); Li et al., NPG Asia Mater. 4, e30 (2012)
# C    5.47  experimental indirect gap of diamond; Clark, Dean, Harris, Proc. R. Soc. A 277, 312 (1964)
LITERATURE_GAPS_EV = {"BN": 6.08, "SnO2": 3.6, "C": 5.47}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--raw-dir", type=Path, required=True, help="archive directory 02_bandgap")
    parser.add_argument("--out", type=Path, default=EXPERIMENT_DIR / "results" / "deviation_evidence.csv")
    args = parser.parse_args()
    warnings.filterwarnings("ignore")

    rows = []
    for system in SYSTEMS:
        ref_dir = args.raw_dir / "pymatgen_reference" / system / "hse06_scf"
        agent_dir = agent_hse_dir(args.raw_dir / "vasp_agent" / system)
        ref_run = Vasprun(ref_dir / "vasprun.xml", parse_potcar_file=False, parse_dos=False)
        agent_run = Vasprun(agent_dir / "vasprun.xml", parse_potcar_file=False, parse_dos=False)
        ref, agent = band_edges(ref_run), band_edges(agent_run)

        # Gap in the Agent output evaluated at the reference band-edge k-point pair.
        iv = find_kpoint(agent["kpoints"], ref["kpoints"][ref["vbm_k"]])
        ic = find_kpoint(agent["kpoints"], ref["kpoints"][ref["cbm_k"]])
        pair_gap = None if iv is None or ic is None else float(agent["unocc_min"][ic] - agent["occ_max"][iv])

        lit_gap = LITERATURE_GAPS_EV.get(system)
        rows.append(
            {
                "system": system,
                "reference_gap_ev": round(ref["gap"], 4),
                "agent_gap_ev": round(agent["gap"], 4),
                "delta_gap_ev": round(agent["gap"] - ref["gap"], 4),
                "reference_kpoint_mesh": kpoint_mesh(ref_dir),
                "agent_kpoint_mesh": kpoint_mesh(agent_dir),
                "reference_encut": incar_value(ref_dir, "ENCUT"),
                "agent_encut": incar_value(agent_dir, "ENCUT"),
                "reference_precfock": effective_precfock(ref_dir),
                "agent_precfock": effective_precfock(agent_dir),
                "reference_vbm_k": kfmt(ref["kpoints"][ref["vbm_k"]]),
                "reference_cbm_k": kfmt(ref["kpoints"][ref["cbm_k"]]),
                "agent_vbm_k": kfmt(agent["kpoints"][agent["vbm_k"]]),
                "agent_cbm_k": kfmt(agent["kpoints"][agent["cbm_k"]]),
                "agent_gap_at_reference_edge_pair_ev": "" if pair_gap is None else round(pair_gap, 4),
                "literature_gap_ev": "" if lit_gap is None else lit_gap,
                "agent_minus_literature_ev": "" if lit_gap is None else round(agent["gap"] - lit_gap, 4),
                "reference_minus_literature_ev": "" if lit_gap is None else round(ref["gap"] - lit_gap, 4),
            }
        )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    for row in rows:
        print(row)


if __name__ == "__main__":
    main()
